static void test_full_table(void) {
    for (int dl = 0; dl < 256; ++dl) {
        uint8_t got = captive_gm_translate_cell((uint8_t)dl, 0u, 1u);
        if (got != GM_XLATE_DH0_AX1[dl]) {
            fprintf(stderr, "mismatch dl=0x%02x: got 0x%02x want 0x%02x\n",
                    dl, got, GM_XLATE_DH0_AX1[dl]);
            assert(got == GM_XLATE_DH0_AX1[dl]);
        }
    }
}

static void test_dh_dependent(void) {
    /* Door (0x22): bl = 0x10 + ((dh>>1)&3), captured from GM. */
    assert(captive_gm_translate_cell(0x22u, 6u, 1u) == 0x13u);
    assert(captive_gm_translate_cell(0x22u, 0u, 1u) == 0x10u);
    assert(captive_gm_translate_cell(0x22u, 2u, 1u) == 0x11u);
    /* 0x2C: bl = dh. */
    assert(captive_gm_translate_cell(0x2Cu, 7u, 1u) == 0x07u);
    /* 0x15: bl = dh + 0x40. */
    assert(captive_gm_translate_cell(0x15u, 9u, 1u) == 0x49u);
}

static void test_ax_dependent(void) {
    /* The 0x1E case is tested BEFORE the ax==0xFFFF exit, so it still wins. */
    assert(captive_gm_translate_cell(0x1Eu, 0u, 0xFFFFu) == 0x18u);
    /* A code with no earlier match, under ax==0, falls to the bl=0 exit. */
    assert(captive_gm_translate_cell(0x33u, 0u, 0x0000u) == 0x00u);
    assert(captive_gm_translate_cell(0x33u, 0u, 0xFFFDu) == 0x00u);
    /* Same code with a normal selector translates normally (0x33 -> 0x60). */
    assert(captive_gm_translate_cell(0x33u, 0u, 1u) == 0x60u);
}

static void test_marker_bit(void) {
    /* High bit is stripped, translated, then OR'd back (except the 0x20 early
     * path).  0x80|0x1E -> 0x18 | 0x80 = 0x98. */
    assert(captive_gm_translate_cell(0x80u | 0x1Eu, 0u, 1u) == 0x98u);
    /* 0x20 returns 0xA0 with no marker OR even when the input carries 0x80. */
    assert(captive_gm_translate_cell(0x20u, 0u, 1u) == 0xA0u);
}

static void test_wall_predicate(void) {
    assert(captive_gm_cell_is_wall(0xA0u));   /* wall (from source 0x20) */
    assert(!captive_gm_cell_is_wall(0x18u));  /* open */
    assert(!captive_gm_cell_is_wall(0x00u));  /* empty */
    assert(captive_gm_cell_is_wall(0x80u | 0x60u)); /* marker masked off first */
}

int main(void) {
    test_full_table();
    test_dh_dependent();
    test_ax_dependent();
    test_marker_bit();
    test_wall_predicate();
    printf("captive_gm_translate: all tests passed\n");
    return 0;
}
